#!/usr/bin/env node
/**
 * Builds JSON from content/courses/*.md (authoring format: content/FORMAT.md).
 *   npm run courses:build
 *
 * - content/courses.json         FULL content, for the backend (answers, explanations, hints, mentor notes, rubrics).
 * - content/courses.public.json  SAFE for the browser: no answers, explanations, hints, mentor notes or example prompts.
 *
 * Lesson `blocks` keep the authoring order: cards and exercises interleaved as written.
 * Run `npm run courses:check` first; this script assumes valid files.
 */
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

import { parse } from "yaml";

const DIR = "content/courses";

function parseCourse(text) {
  const fm = text.match(/^---\n([\s\S]*?)\n---\n/);
  const meta = parse(fm[1]);
  const lessonParts = text.split(/\n## Lesson \d+: /).slice(1);
  const lessons = lessonParts.map((part) => {
    const title = part.slice(0, part.indexOf("\n")).trim();
    const body = part.slice(part.indexOf("\n"));
    const tokens = [
      ...[...body.matchAll(/\n### Card: (.+)\n([\s\S]*?)(?=\n### |\n```yaml |$)/g)].map((m) => ({
        index: m.index,
        type: "card",
        data: { title: m[1].trim(), body: m[2].trim() },
      })),
      ...[...body.matchAll(/```yaml (lesson|exercise|practice|mentor)\n([\s\S]*?)\n```/g)].map((m) => ({
        index: m.index,
        type: m[1],
        data: parse(m[2]),
      })),
    ].sort((a, b) => a.index - b.index);

    const lesson = tokens.find((t) => t.type === "lesson")?.data ?? {};
    return {
      ...lesson,
      title,
      blocks: tokens
        .filter((t) => t.type === "card" || t.type === "exercise")
        .map((t) => (t.type === "card" ? { type: "card", ...t.data } : { ...t.data, block: "exercise" })),
      practice: tokens.find((t) => t.type === "practice")?.data ?? null,
      mentor: tokens.find((t) => t.type === "mentor")?.data ?? null,
    };
  });
  return { ...meta, lessons };
}

const HIDDEN_EXERCISE_FIELDS = ["answer", "answers", "explanation", "hint"];

function toPublic(course) {
  return {
    ...course,
    lessons: course.lessons.map(({ practice, ...rest }) => {
      const lesson = { ...rest };
      delete lesson.mentor;
      return {
        ...lesson,
        blocks: lesson.blocks.map((block) => {
          if (block.block !== "exercise") return block;
          const safe = Object.fromEntries(
            Object.entries(block).filter(([k]) => !HIDDEN_EXERCISE_FIELDS.includes(k)),
          );
          if (Array.isArray(safe.cards)) safe.cards = safe.cards.map(({ statement }) => ({ statement }));
          return safe;
        }),
        practice: practice && {
          id: practice.id,
          skill: practice.skill,
          instructions: practice.instructions,
          rubric: practice.rubric,
        },
      };
    }),
  };
}

const files = (await readdir(DIR)).filter((f) => f.endsWith(".md")).sort();
const courses = [];
for (const f of files) courses.push(parseCourse(await readFile(path.join(DIR, f), "utf8")));

const stamp = {
  generated_from: "content/courses/*.md",
  note: "Generated by npm run courses:build. Do not edit.",
};
await writeFile("content/courses.json", JSON.stringify({ ...stamp, courses }, null, 2) + "\n");
await writeFile(
  "content/courses.public.json",
  JSON.stringify({ ...stamp, courses: courses.map(toPublic) }, null, 2) + "\n",
);

const lessons = courses.reduce((n, c) => n + c.lessons.length, 0);
console.log(
  `Built ${courses.length} courses, ${lessons} lessons → content/courses.json, content/courses.public.json`,
);
